#!/usr/bin/env node
// Signs the MusicKit "developer token" (a JWT) from your Apple Developer MusicKit
// private key. This has to happen somewhere that holds the .p8 private key, which
// must never reach public-am/ or any client-side file — hence this standalone
// script instead of doing it in app.js. Uses only Node's built-in crypto module,
// matching the project's no-dependencies philosophy.
//
// Usage:
//   node tools/apple-dev-token.js --team <TEAM_ID> --key <KEY_ID> --p8 <path/to/AuthKey_KEYID.p8>
//
// TEAM_ID and KEY_ID come from developer.apple.com/account (Membership details,
// and Certificates/Identifiers/Profiles > Keys). Re-run this before the token
// expires (Apple caps it at 6 months) — there's no auto-refresh.
"use strict";
const fs = require("fs");
const crypto = require("crypto");
const path = require("path");

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? fallback : process.argv[i + 1];
}

const teamId = arg("team");
const keyId = arg("key");
const p8Path = arg("p8");
const days = Math.min(Number(arg("days", "180")), 182); // Apple rejects exp beyond ~6 months
const outPath = arg("out", path.join(__dirname, "..", "public-am", "config.js"));

if (!teamId || !keyId || !p8Path) {
  console.error(
    "Usage: node tools/apple-dev-token.js --team <TEAM_ID> --key <KEY_ID> --p8 <path/to/AuthKey_KEYID.p8> [--days 180] [--out path]",
  );
  process.exit(1);
}

const b64url = (buf) => buf.toString("base64").replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");

const now = Math.floor(Date.now() / 1000);
const exp = now + days * 86400;

const header = b64url(Buffer.from(JSON.stringify({ alg: "ES256", kid: keyId })));
const payload = b64url(Buffer.from(JSON.stringify({ iss: teamId, iat: now, exp })));
const signingInput = `${header}.${payload}`;

const privateKey = fs.readFileSync(p8Path, "utf8");
// ES256 (JWS) wants a raw R||S signature, not the DER encoding crypto.sign gives
// by default — dsaEncoding: "ieee-p1363" is what gets the raw form out of Node.
const signature = crypto.sign("sha256", Buffer.from(signingInput), { key: privateKey, dsaEncoding: "ieee-p1363" });
const token = `${signingInput}.${b64url(signature)}`;

const today = new Date(now * 1000).toISOString().slice(0, 10);
const expiry = new Date(exp * 1000).toISOString().slice(0, 10);
const out = `// Generated by tools/apple-dev-token.js on ${today}. Expires ${expiry}.
// Do not commit this file (it's gitignored) and don't paste this token anywhere public.
window.APPLE_DEVELOPER_TOKEN = "${token}";
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`Wrote developer token to ${outPath} (expires ${expiry}).`);
